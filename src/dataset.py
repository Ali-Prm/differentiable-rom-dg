"""
Dataset for parameterized periodic Burgers FOM snapshots.

Reads the flat HDF5 generated by generate_data.jl:
  - u       : (n_samples, n_times, Nx) solution snapshots
  - x / x_coords : (Nx,) physical GLL node coordinates
  - w / quad_weights : (Nx,) physical GLL quadrature weights
  - t       : (n_times,) snapshot timestamps
  - mu1, mu2: (n_samples,) trajectory parameters
"""

from __future__ import annotations
from pathlib import Path
from typing import Optional

import h5py
import numpy as np
import torch
from torch.utils.data import Dataset


def _compute_gll_weights(K: int, polydeg: int) -> np.ndarray:
    """Analytical GLL reference weights scaled by element Jacobian J = 1/(2K)."""
    # Reference Gauss-Lobatto-Legendre weights on [-1, 1]
    if polydeg == 1:
        w_ref = np.array([1.0, 1.0], dtype=np.float64)
    elif polydeg == 2:
        w_ref = np.array([1.0 / 3.0, 4.0 / 3.0, 1.0 / 3.0], dtype=np.float64)
    elif polydeg == 3:
        w_ref = np.array([1.0 / 6.0, 5.0 / 6.0, 5.0 / 6.0, 1.0 / 6.0], dtype=np.float64)
    elif polydeg == 4:
        w_ref = np.array([0.1, 49.0 / 90.0, 32.0 / 45.0, 49.0 / 90.0, 0.1], dtype=np.float64)
    else:
        # General GLL nodes & weights via Chebyshev-Lobatto initial guess / Legendre poly roots
        from numpy.polynomial.legendre import Legendre
        P = Legendre.basis(polydeg)
        P_deriv = P.deriv()
        roots = P_deriv.roots()
        nodes = np.concatenate(([-1.0], roots, [1.0]))
        P_vals = P(nodes)
        w_ref = 2.0 / (polydeg * (polydeg + 1) * (P_vals ** 2))

    J = 1.0 / (2.0 * K)
    w_elem = w_ref * J
    return np.tile(w_elem, K)


class BurgersSnapshotDataset(Dataset):
    def __init__(
        self,
        h5_path: str,
        subsample_t: int = 1,
        dtype: torch.dtype = torch.float32,
    ):
        if subsample_t < 1:
            raise ValueError(f"subsample_t must be >= 1, got {subsample_t}")

        self.h5_path = str(Path(h5_path))
        self.dtype = dtype

        with h5py.File(self.h5_path, "r") as f:
            # 1. Read Mesh metadata
            if "K" in f:
                self.K = int(np.asarray(f["K"]).item())
            elif "K" in f.attrs:
                self.K = int(f.attrs["K"])
            else:
                self.K = 128

            if "polydeg" in f:
                self.polydeg = int(np.asarray(f["polydeg"]).item())
            elif "polydeg" in f.attrs:
                self.polydeg = int(f.attrs["polydeg"])
            else:
                self.polydeg = 3

            # 2. Coordinates
            if "x" in f:
                x_coords = np.asarray(f["x"][:], dtype=np.float64)
            elif "x_coords" in f:
                x_coords = np.asarray(f["x_coords"][:], dtype=np.float64)
            else:
                raise KeyError("HDF5 file must contain 'x' or 'x_coords' dataset.")

            self.Nx = len(x_coords)
            self.x_coords = torch.from_numpy(x_coords).to(dtype)

            # 3. Quadrature weights
            if "w" in f:
                quad_weights = np.asarray(f["w"][:], dtype=np.float64)
            elif "quad_weights" in f:
                quad_weights = np.asarray(f["quad_weights"][:], dtype=np.float64)
            else:
                quad_weights = _compute_gll_weights(self.K, self.polydeg)

            self.quad_weights = torch.from_numpy(quad_weights).to(dtype)

            # 4. Snapshots & Parameters
            u_raw = np.asarray(f["u"][:], dtype=np.float32)
            # Handle Julia column-major ordering (Nx, Nt, N_samples) -> (N_samples, Nt, Nx)
            if u_raw.ndim == 3:
                if u_raw.shape[0] == self.Nx and u_raw.shape[2] != self.Nx:
                    u_raw = u_raw.transpose(2, 1, 0)
                elif u_raw.shape[1] == self.Nx:
                    u_raw = u_raw.transpose(0, 2, 1)

            n_samples, n_times, nx_dim = u_raw.shape
            if nx_dim != self.Nx:
                raise ValueError(f"State dimension mismatch: got {nx_dim}, expected {self.Nx}")

            t_raw = np.asarray(f["t"][:], dtype=np.float32).reshape(-1) if "t" in f else np.linspace(0, 1, n_times, dtype=np.float32)

            # Parameters mu1, mu2
            if "mu1" in f and "mu2" in f:
                mu1 = np.asarray(f["mu1"][:], dtype=np.float32).reshape(-1)
                mu2 = np.asarray(f["mu2"][:], dtype=np.float32).reshape(-1)
                params_raw = np.stack([mu1, mu2], axis=-1)
            elif "params" in f:
                params_raw = np.asarray(f["params"][:], dtype=np.float32)
            else:
                params_raw = np.zeros((n_samples, 2), dtype=np.float32)

        # 5. Flatten trajectories over time
        all_snaps, all_params, all_sim_ids, all_times, all_time_idx = [], [], [], [], []

        for sim_id in range(n_samples):
            snaps_sub = u_raw[sim_id, ::subsample_t, :]
            times_sub = t_raw[::subsample_t]
            nt = snaps_sub.shape[0]

            all_snaps.append(snaps_sub)
            all_params.append(np.repeat(params_raw[sim_id : sim_id + 1, :], nt, axis=0))
            all_sim_ids.append(np.full(nt, sim_id, dtype=np.int64))
            all_times.append(times_sub)
            all_time_idx.append(np.arange(nt, dtype=np.int64))

        self._snaps = np.concatenate(all_snaps, axis=0)
        self._params = np.concatenate(all_params, axis=0)
        self._sim_ids = np.concatenate(all_sim_ids, axis=0)
        self._times = np.concatenate(all_times, axis=0)
        self._time_indices = np.concatenate(all_time_idx, axis=0)
        self._N = self._snaps.shape[0]
        self.n_parameters = self._params.shape[1]

    def __len__(self) -> int:
        return self._N

    def __getitem__(self, idx: int) -> dict:
        return {
            "U": torch.from_numpy(self._snaps[idx]).to(self.dtype),
            "params": torch.from_numpy(self._params[idx]).to(self.dtype),
            "sim_id": torch.tensor(self._sim_ids[idx], dtype=torch.long),
            "time": torch.tensor(self._times[idx], dtype=self.dtype),
            "time_index": torch.tensor(self._time_indices[idx], dtype=torch.long),
            "idx": torch.tensor(idx, dtype=torch.long),
        }

    @property
    def sample_sim_ids(self) -> np.ndarray:
        return self._sim_ids